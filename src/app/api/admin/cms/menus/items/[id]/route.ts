import { NextRequest } from "next/server";
import { assertSameOrigin, ok, parseBody, route } from "@/lib/http";
import { requirePermission } from "@/lib/auth/session";
import { deleteMenuItem, updateMenuItem } from "@/services/cms";
import { menuItemUpdateSchema } from "@/lib/validation";

export const runtime = "nodejs";
type Context = { params: Promise<{ id: string }> };

export const PATCH = route(async (request: NextRequest, context) => {
  assertSameOrigin(request);
  const user = await requirePermission("cms.manage");
  const { id } = await (context as Context).params;
  const input = await parseBody(request, menuItemUpdateSchema);
  await updateMenuItem(id, {
    ...input,
    ...(input.parentId !== undefined ? { parentId: input.parentId ? input.parentId : null } : {}),
  }, user.id);
  return ok({ updated: true });
});

export const DELETE = route(async (request: NextRequest, context) => {
  assertSameOrigin(request);
  const user = await requirePermission("cms.manage");
  const { id } = await (context as Context).params;
  await deleteMenuItem(id, user.id);
  return ok({ deleted: true });
});
